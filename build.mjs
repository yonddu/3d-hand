// Builds two entry pages from app.html:
//   index.html            standalone app, every dependency served from ./vendor (works offline / any static host)
//   dist/artifact/        single-page build for claude.ai Artifacts (libraries from jsDelivr, wasm + model as files)
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { build } from 'esbuild';

const MP_VERSION = '0.10.21';
const THREE_VERSION = '0.170.0';
const body = readFileSync('app.html', 'utf8');

const importMap = (imports) => `<script type="importmap">${JSON.stringify({ imports }, null, 2)}</script>`;
const config = (cfg) => `<script>window.HMS_CONFIG = ${JSON.stringify(cfg)};</script>`;

// --- standalone -------------------------------------------------------------
const standalone = `<!doctype html>
<html lang="ko">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px);box-sizing:border-box}body{margin:0}[hidden]{display:none!important}</style>
</head>
<body>
<!-- Generated by build.mjs from app.html. Edit app.html / src/, then run: npm run build -->
${body}
${config({ wasmBase: 'vendor/mediapipe/wasm', modelPath: 'vendor/models/hand_landmarker.task' })}
${importMap({
  three: './vendor/three/three.module.min.js',
  'three/addons/': './vendor/three/addons/',
  '@mediapipe/tasks-vision': './vendor/mediapipe/vision_bundle.mjs',
})}
<script type="module" src="src/main.js"></script>
</body>
</html>
`;
writeFileSync('index.html', standalone);

// --- artifact ---------------------------------------------------------------
const out = 'dist/artifact';
mkdirSync(out, { recursive: true });
const bundle = await build({
  entryPoints: ['src/main.js'],
  bundle: true,
  format: 'esm',
  write: false,
  minify: true,
  external: ['three', 'three/addons/*', '@mediapipe/tasks-vision'],
});
const js = bundle.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const jsd = 'https://cdn.jsdelivr.net/npm';
const artifact = `${body}
${config({
  wasmLoaderPath: `${jsd}/@mediapipe/tasks-vision@${MP_VERSION}/wasm/vision_wasm_internal.js`,
  wasmBinaryPath: 'vision_wasm_internal.wasm',
  modelBase64Path: 'hand_landmarker.task.b64.txt',
})}
${importMap({
  three: `${jsd}/three@${THREE_VERSION}/build/three.module.min.js`,
  'three/addons/': `${jsd}/three@${THREE_VERSION}/examples/jsm/`,
  '@mediapipe/tasks-vision': `${jsd}/@mediapipe/tasks-vision@${MP_VERSION}/vision_bundle.mjs`,
})}
<script type="module">${js}</script>
`;
writeFileSync(`${out}/index.html`, artifact);
copyFileSync('vendor/mediapipe/wasm/vision_wasm_internal.wasm', `${out}/vision_wasm_internal.wasm`);
// Artifacts serve only web media types, so the model goes as base64 text.
writeFileSync(`${out}/hand_landmarker.task.b64.txt`, readFileSync('vendor/models/hand_landmarker.task').toString('base64'));
console.log('built index.html and dist/artifact/');
